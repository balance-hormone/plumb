/** The first line of every file Plumb writes, so it can tell its files from others. */
export const MARKER = '// Generated by Plumb';
const WIDTH = 100;

/** The line in a runtime file after which a generated file holds it as written. */
const CUT = '// Generated files hold what follows this line.\n';
const embed = (source: string) => source.slice(source.indexOf(CUT) + CUT.length);

const HELPERS = `${MARKER}. Do not edit.\n${embed(plumbSource)}`;

// Only with Questionnaires in content, so a project without any has no unused export.
const ANSWERS = `\n${embed(answersSource)}`;

