// Print: every formatting rule lives here. A pure function from the type
// model to text, with no FHIR knowledge.
import { FileBuilder, wordWrap } from '@medplum/core';
import type { Route, Routing } from './routes.js';
import type { Field, Helper, ProfileModel, TypeExpr } from './transform.js';

/** The first line of every file Plumb writes, so it can tell its files from others. */
export const MARKER = '// Generated by Plumb';
const WIDTH = 100;

const HELPERS = `${MARKER}. Do not edit.
/** \`T\` with the keys \`K\` required, and never \`undefined\`. */
export type Require<T, K extends keyof T> = Omit<T, K> & { [P in K]-?: NonNullable<T[P]> };

/** \`Omit\` over each member of a union, so an exactly-one-of type stays one. */
export type OmitEach<T, K extends PropertyKey> = T extends unknown ? Omit<T, K> : never;

/**
 * Whether \`value\` holds everything in \`pattern\`, as FHIR matches a slice's
 * discriminator: an array in the pattern means each entry appears somewhere, and
 * a single pattern against an array is met by any entry.
 */
export function matches(value: unknown, pattern: unknown): boolean {
  if (Array.isArray(value) && !Array.isArray(pattern)) return value.some((v) => matches(v, pattern));
  if (Array.isArray(pattern)) {
    return Array.isArray(value) && pattern.every((p) => value.some((v) => matches(v, p)));
  }
  if (pattern !== null && typeof pattern === 'object') {
    if (value === null || typeof value !== 'object') return false;
    const record = value as Record<string, unknown>;
    return Object.entries(pattern).every(([key, p]) => matches(record[key], p));
  }
  return value === pattern;
}
`;

const quote = (text: string) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const indentRest = (text: string, by: string) => text.replaceAll('\n', `\n${by}`);
const needsParens = (t: TypeExpr) => t.kind === 'union' || t.kind === 'narrow';
const paren = (t: TypeExpr) => (needsParens(t) ? `(${printExpr(t)})` : printExpr(t));

function docLines(text: string[], width: number): string[] {
  const body = text.flatMap((line) =>
    line ? wordWrap(line.replaceAll('*/', '*\\/'), width) : [''],
  );
  return ['/**', ...body.map((line) => (line ? ` * ${line}` : ' *')), ' */'];
}

function printField(field: Field): string {
  const line = `${field.name}${field.optional ? '?' : ''}: ${printExpr(field.type)};`;
  if (!field.doc) return line;
  const doc = `/** ${field.doc.replaceAll('*/', '*\\/')} */`;
  const lines = doc.length <= WIDTH - 2 ? [doc] : docLines([field.doc], WIDTH - 5);
  return [...lines, line].join('\n');
}

function block(fields: Field[]): string {
  if (fields.length === 0) return '{}';
  return `{\n${fields.map((f) => `  ${indentRest(printField(f), '  ')}`).join('\n')}\n}`;
}

/** Joins keys with ' | ' into lines no wider than `width`. */
function fill(keys: string[], width: number): string[] {
  const lines: string[] = [];
  for (const key of keys) {
    const last = lines.at(-1);
    if (last !== undefined && last.length + key.length + 3 <= width)
      lines[lines.length - 1] = `${last} | ${key}`;
    else lines.push(key);
  }
  return lines;
}

/** A type expression as TypeScript; nested lines are indented relative to the first. */
export function printExpr(t: TypeExpr): string {
  switch (t.kind) {
    case 'ref':
      return t.args ? `${t.name}<${t.args.map(printExpr).join(', ')}>` : t.name;
    case 'primitive':
      return t.name;
    case 'index':
      return `NonNullable<${t.base}[${quote(t.key)}]>`;
    case 'literal':
      return typeof t.value === 'string' ? quote(t.value) : String(t.value);
    case 'array':
      return `${paren(t.of)}[]`;
    case 'tuple':
      return `[${t.of.map(printExpr).join(', ')}]`;
    case 'optional':
      return `${paren(t.of)}?`;
    case 'rest':
      return `...${paren(t.of)}[]`;
    case 'union':
      return t.of.map(paren).join(' | ');
    case 'object':
      return block(t.fields);
    case 'require':
      return `Require<${printExpr(t.base)}, ${t.keys.map(quote).join(' | ')}>`;
    case 'never':
      return 'never';
    case 'otherString':
      return '(string & {})';
    case 'narrow': {
      const base = printExpr(t.base);
      const keys = t.omit.map(quote);
      const inline = `Omit<${base}, ${keys.join(' | ')}>`;
      // A long list goes one key per line, so the file stays readable.
      const omitted =
        keys.length === 0
          ? base
          : inline.length <= 80
            ? inline
            : `Omit<\n  ${base},\n${fill(keys, WIDTH - 4)
                .map((line) => `  | ${line}`)
                .join('\n')}\n>`;
      const groups = (t.oneOf ?? []).map(
        (branches) =>
          ` & (\n${branches.map((b) => `  | ${indentRest(block(b), '    ')}`).join('\n')}\n)`,
      );
      return `${omitted} & ${block(t.fields)}${groups.join('')}`;
    }
  }
}

/** Every type name an expression refers to. */
function names(t: TypeExpr, into: Set<string>): Set<string> {
  switch (t.kind) {
    case 'ref':
      into.add(t.name);
      for (const arg of t.args ?? []) names(arg, into);
      break;
    case 'index':
      into.add(t.base);
      break;
    case 'array':
    case 'optional':
    case 'rest':
      names(t.of, into);
      break;
    case 'tuple':
    case 'union':
      for (const item of t.of) names(item, into);
      break;
    case 'object':
      for (const f of t.fields) names(f.type, into);
      break;
    case 'require':
      into.add('Require');
      names(t.base, into);
      break;
    case 'narrow':
      names(t.base, into);
      for (const f of [...t.fields, ...(t.oneOf ?? []).flat(2)]) names(f.type, into);
      break;
  }
  return into;
}

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

/** A JSON value as a TypeScript expression. */
function printValue(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(printValue).join(', ')}]`;
  if (value !== null && typeof value === 'object') {
    const entries = Object.entries(value).map(
      ([key, v]) => `${IDENTIFIER.test(key) ? key : quote(key)}: ${printValue(v)}`,
    );
    return `{ ${entries.join(', ')} }`;
  }
  return typeof value === 'string' ? quote(value) : String(value);
}

function printHelper(h: Helper): string[] {
  const keys = Object.keys(h.values);
  if (h.kind === 'build') {
    return [
      `  /** ${/^[aeiou]/i.test(h.element) ? 'An' : 'A'} ${h.element} entry in the ${h.slice} slice, with ${keys.join(' and ')} filled in. */`,
      `  ${h.name}: (entry: OmitEach<${h.shape}, ${keys.map(quote).join(' | ')}>): ${h.shape} => ({`,
      '    ...entry,',
      ...keys.map((key) => `    ${key}: ${printValue(h.values[key])},`),
      '  }),',
    ];
  }
  return [
    `  /** The first ${h.element} entry in the ${h.slice} slice, if there is one. */`,
    `  ${h.name}: (parent: { ${h.element}?: ${h.item}[] }): ${h.shape} | undefined =>`,
    `    parent.${h.element}?.find((e): e is ${h.shape} => matches(e, ${printValue(h.values)})),`,
  ];
}

/** Which file declares each generated type, so a file can import another's. */
type Owners = Map<string, string>;

function printProfile(model: ProfileModel, hash: string, owners: Owners): string {
  const b = new FileBuilder('  ', false);
  const version = model.version ? `|${model.version}` : '';
  b.appendNoWrap(`${MARKER} from ${model.url}${version}. Do not edit.`);
  b.appendNoWrap(`// Source: ${model.source} ${hash}`);
  const used = new Set<string>();
  for (const d of model.decls) names(d.type, used);
  for (const h of model.helpers) used.add(h.item);
  const local = new Set(model.decls.map((d) => d.name));
  const foreign = [...used].filter((n) => !local.has(n) && n !== 'Require');
  const fhir = foreign.filter((n) => !owners.has(n)).sort();
  if (fhir.length > 0)
    b.appendNoWrap(`import type { ${fhir.join(', ')} } from '@medplum/fhirtypes';`);
  const files = [...new Set(foreign.flatMap((n) => owners.get(n) ?? []))].sort();
  for (const file of files) {
    const names = foreign.filter((n) => owners.get(n) === file).sort();
    b.appendNoWrap(`import type { ${names.join(', ')} } from './${file}.js';`);
  }
  const plumb = [
    ...(model.helpers.length > 0 ? ['matches'] : []),
    ...(model.helpers.some((h) => h.kind === 'build') ? ['type OmitEach'] : []),
    ...(used.has('Require') ? ['type Require'] : []),
  ];
  if (plumb.length > 0) b.appendNoWrap(`import { ${plumb.join(', ')} } from './_plumb.js';`);
  b.newLine();
  b.appendNoWrap(`/** The canonical URL of ${model.typeName}. */`);
  b.appendNoWrap(`export const ${model.typeName}ProfileUrl = ${quote(model.url)};`);
  for (const constant of model.constants) {
    b.newLine();
    b.appendNoWrap(`/** The codes of ${constant.name.slice(0, -'Codes'.length)}. */`);
    b.appendNoWrap(`export const ${constant.name} = [`);
    for (const c of constant.codes) b.appendNoWrap(`  ${printValue(c)},`);
    b.appendNoWrap('] as const;');
  }
  model.decls.forEach((d, i) => {
    b.newLine();
    if (i === 0) for (const line of docLines(model.doc, WIDTH - 3)) b.appendNoWrap(line);
    for (const line of `export type ${d.name} = ${printExpr(d.type)};`.split('\n'))
      b.appendNoWrap(line);
  });
  if (model.helpers.length > 0) {
    b.newLine();
    b.appendNoWrap(`/** Builders and readers for the slices of ${model.typeName}. */`);
    b.appendNoWrap(`export const ${model.typeName} = {`);
    for (const line of model.helpers.flatMap(printHelper)) b.appendNoWrap(line);
    b.appendNoWrap('};');
  }
  return b.toString();
}

const ROUTE = `interface Row {
  readonly profile: ProfileUrl;
  readonly parents: readonly string[];
  readonly keys: readonly (readonly [string, readonly unknown[]])[];
}

/** Thrown when no selected profile, or several unrelated ones, match a resource. */
export class RoutingError extends Error {
  /** The profiles that matched, or every routed profile on the type when none did. */
  readonly candidates: readonly ProfileUrl[];
  constructor(message: string, candidates: readonly ProfileUrl[]) {
    super(message);
    this.name = 'RoutingError';
    this.candidates = candidates;
  }
}

/**
 * The selected profile a resource's content selects: every row whose keys all
 * match, less any that is a parent of another match. \`undefined\` when no
 * selected profile constrains the resource's type. Throws a RoutingError when
 * none, or several unrelated ones, match: it never guesses.
 */
export function route(resource: Resource): ProfileUrl | undefined {
  const table: Partial<Record<string, readonly Row[]>> = routes;
  const rows = table[resource.resourceType];
  if (!rows) return undefined;
  const fields = resource as unknown as Record<string, unknown>;
  const matched = rows.filter((row) =>
    row.keys.every(([element, patterns]) => patterns.some((p) => matches(fields[element], p))),
  );
  const best = matched.filter((row) => !matched.some((other) => other.parents.includes(row.profile)));
  if (best.length === 1) return best[0]?.profile;
  const type = resource.resourceType;
  const shown = best.length === 0 ? rows : best;
  const width = Math.max(0, ...shown.map((row) => short(row.profile).length));
  throw new RoutingError(
    [
      best.length === 0
        ? \`no profile matches this \${type}.\`
        : \`\${best.length} unrelated profiles match this \${type}.\`,
      ...shown.map((row) => \`  \${short(row.profile).padEnd(width)}   \${needs(row, type)}\`),
      'Pass { profile } to choose one, or { profile: false } to write it unprofiled.',
    ].join('\\n'),
    shown.map((row) => row.profile),
  );
}

const short = (url: string) => url.slice(url.lastIndexOf('/') + 1);

function needs(row: Row, type: string): string {
  if (row.keys.length === 0) return \`matches any \${type}\`;
  return \`needs \${row.keys.map(([element, patterns]) => \`\${element} \${patterns.map(describe).join(' or ')}\`).join(', ')}\`;
}

/** A pattern as a reader would say it: a coding as system|code, an object by its fields. */
function describe(pattern: unknown): string {
  if (typeof pattern !== 'object' || pattern === null) return String(pattern);
  const { system, code, coding } = pattern as { system?: unknown; code?: unknown; coding?: unknown };
  if (Array.isArray(coding)) return coding.map(describe).join(' and ');
  if (typeof code === 'string' && Object.keys(pattern).every((k) => ['system', 'code', 'display'].includes(k))) {
    return typeof system === 'string' ? \`\${system}|\${code}\` : code;
  }
  return Object.entries(pattern)
    .map(([key, value]) => \`\${key} \${describe(value)}\`)
    .join(', ');
}
`;

const WRITE = `/**
 * The part of a \`MedplumClient\` the writes use, so the generated code needs no
 * \`@medplum/core\` declarations of its own: a MedplumClient is one.
 */
export interface ProfiledClient {
  createResource<T extends Resource>(resource: T): Promise<T>;
  updateResource<T extends Resource>(resource: T): Promise<T>;
}

/** What a write to each selected profile stamps: the type's defaults it does not derive from, then the profile. */
const stamps: Record<ProfileUrl, readonly string[]> = STAMPS;

/** Every URL Plumb stamps. A write replaces these in \`meta.profile\`, and keeps any other. */
const managed: ReadonlySet<string> = new Set<string>(MANAGED);

/**
 * A copy of the resource stamped for the profile: the URLs Plumb does not
 * manage, then the profile's stamps. With no profile, only the other URLs
 * stay, and an empty \`meta.profile\` is left out: it would skip the server's
 * \`defaultProfile\`.
 */
function stamped<T extends Resource>(resource: T, profile: ProfileUrl | false | undefined): T {
  const { profile: current = [], ...meta } = resource.meta ?? {};
  const kept = current.filter((url) => !managed.has(url.split('|')[0] ?? url));
  const profiles = [...kept, ...(profile ? stamps[profile] : [])];
  const { meta: _, ...rest } = resource;
  if (profiles.length > 0) return { ...rest, meta: { ...meta, profile: profiles } } as T;
  return (Object.keys(meta).length > 0 ? { ...rest, meta } : rest) as T;
}

/**
 * Creates the resource held to the profile its content selects, stamped with
 * that profile and the project's defaults. \`{ profile }\` chooses one instead,
 * and \`{ profile: false }\` writes it with no Plumb stamp, so the server's own
 * default applies. Rejects with a RoutingError, before anything is written,
 * when the content selects no single profile. The resource passed is not changed.
 */
export function createProfiled<U extends ProfileUrl>(
  medplum: ProfiledClient,
  resource: ProfileTypes[U],
  options: { profile: U },
): Promise<ProfileTypes[U]>;
export function createProfiled<T extends Resource>(
  medplum: ProfiledClient,
  resource: T,
  options?: { profile: false },
): Promise<T>;
export async function createProfiled(
  medplum: ProfiledClient,
  resource: Resource,
  options: { profile?: ProfileUrl | false } = {},
): Promise<Resource> {
  return medplum.createResource(stamped(resource, options.profile ?? route(resource)));
}

/**
 * Updates the resource held to the profile its new content selects: the
 * stamps Plumb manages are replaced, and any other URL in \`meta.profile\` is
 * kept. Options and errors as createProfiled.
 */
export function updateProfiled<U extends ProfileUrl>(
  medplum: ProfiledClient,
  resource: ProfileTypes[U],
  options: { profile: U },
): Promise<ProfileTypes[U]>;
export function updateProfiled<T extends Resource>(
  medplum: ProfiledClient,
  resource: T,
  options?: { profile: false },
): Promise<T>;
export async function updateProfiled(
  medplum: ProfiledClient,
  resource: Resource,
  options: { profile?: ProfileUrl | false } = {},
): Promise<Resource> {
  return medplum.updateResource(stamped(resource, options.profile ?? route(resource)));
}
`;

/**
 * The routing rows, by resource type then profile URL so a profile change
 * moves only its own lines, with the selected profiles' types and `route`.
 */
function printRoutes(routing: RoutingTable, typeNames: Map<string, string>): string {
  const selected = routing.profiles
    .flatMap((url) => {
      const name = typeNames.get(url);
      return name ? [[url, name] as const] : [];
    })
    .sort(([a], [b]) => a.localeCompare(b));
  const lines = [`${MARKER}. Do not edit.`, "import type { Resource } from '@medplum/fhirtypes';"];
  lines.push("import { matches } from './_plumb.js';");
  for (const name of [...new Set(selected.map(([, n]) => n))].sort()) {
    lines.push(`import type { ${name} } from './${name}.js';`);
  }
  lines.push('', "/** Each selected profile's type, by canonical URL. */");
  if (selected.length === 0) lines.push('export type ProfileTypes = {};');
  else {
    lines.push('export type ProfileTypes = {');
    for (const [url, name] of selected) lines.push(`  ${quote(url)}: ${name};`);
    lines.push('};');
  }
  lines.push(
    '',
    '/** The canonical URL of a selected profile. */',
    'export type ProfileUrl = keyof ProfileTypes;',
    '',
    '/**',
    ' * The content that selects each profile: a row matches a resource when, for',
    ' * every key, the element holds one of its patterns (`matches` in _plumb.ts).',
    ' */',
    'export const routes = {',
    ...Object.keys(routing.routes)
      .sort()
      .flatMap((type) => printRows(type, routing.routes[type] ?? [])),
    '} as const;',
    '',
    ROUTE,
    WRITE.replace('STAMPS', printStamps(routing.stamps)).replace(
      'MANAGED',
      printValue([...routing.managed].sort()),
    ),
  );
  return lines.join('\n');
}

function printRows(type: string, routes: Route[]): string[] {
  if (routes.length === 0) return [`  ${type}: [],`];
  const rows = [...routes].sort((a, b) => a.profile.localeCompare(b.profile));
  return [
    `  ${type}: [`,
    ...rows.flatMap((row) => [
      '    {',
      `      profile: ${quote(row.profile)},`,
      `      parents: ${printValue(row.parents)},`,
      ...(row.keys.length === 0
        ? ['      keys: [],']
        : ['      keys: [', ...row.keys.map((key) => `        ${printValue(key)},`), '      ],']),
      '    },',
    ]),
    '  ],',
  ];
}

type RoutingTable = Pick<Routing, 'routes' | 'profiles' | 'stamps' | 'managed'>;

function printStamps(stamps: Record<string, string[]>): string {
  const urls = Object.keys(stamps).sort();
  if (urls.length === 0) return '{}';
  return `{\n${urls.map((url) => `  ${quote(url)}: ${printValue(stamps[url])},`).join('\n')}\n}`;
}

/** Every file Plumb writes to `out`: one per profile, the index, the shared helpers and the routes. */
export function printFiles(
  models: ProfileModel[],
  hashOf: (model: ProfileModel) => string,
  routing: RoutingTable = { routes: {}, profiles: [], stamps: {}, managed: [] },
): Map<string, string> {
  const owners: Owners = new Map(
    models.flatMap((m) => m.decls.map((d): [string, string] => [d.name, m.typeName])),
  );
  const files = new Map<string, string>();
  for (const model of models) {
    files.set(`${model.typeName}.ts`, printProfile(model, hashOf(model), owners));
  }
  const index = new FileBuilder('  ', false);
  index.appendNoWrap(`${MARKER}. Do not edit.`);
  index.appendNoWrap("export type { Require } from './_plumb.js';");
  index.appendNoWrap(
    "export { createProfiled, type ProfiledClient, type ProfileTypes, type ProfileUrl, RoutingError, route, updateProfiled } from './_routes.js';",
  );
  for (const name of models.map((m) => m.typeName).sort()) {
    index.appendNoWrap(`export * from './${name}.js';`);
  }
  files.set('index.ts', index.toString());
  files.set('_plumb.ts', HELPERS);
  files.set('_routes.ts', printRoutes(routing, new Map(models.map((m) => [m.url, m.typeName]))));
  return files;
}
