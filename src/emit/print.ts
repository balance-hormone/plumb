export const quote = (text: string) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const indentRest = (text: string, by: string) => text.replaceAll('\n', `\n${by}`);
const needsParens = (t: TypeExpr) => t.kind === 'union' || t.kind === 'narrow';
const paren = (t: TypeExpr) => (needsParens(t) ? `(${printExpr(t)})` : printExpr(t));

function docLines(text: string[], width: number): string[] {
  const body = text.flatMap((line) =>
    line ? wordWrap(line.replaceAll('*/', '*\\/'), width) : [''],
  );
  return ['/**', ...body.map((line) => (line ? ` * ${line}` : ' *')), ' */'];
}

function printField(field: Field): string {
  const line = `${field.name}${field.optional ? '?' : ''}: ${printExpr(field.type)};`;
  if (!field.doc) return line;
  const doc = `/** ${field.doc.replaceAll('*/', '*\\/')} */`;
  const lines = doc.length <= WIDTH - 2 ? [doc] : docLines([field.doc], WIDTH - 5);
  return [...lines, line].join('\n');
}

function block(fields: Field[]): string {
  if (fields.length === 0) return '{}';
  return `{\n${fields.map((f) => `  ${indentRest(printField(f), '  ')}`).join('\n')}\n}`;
}

/** Joins keys with ' | ' into lines no wider than `width`. */
function fill(keys: string[], width: number): string[] {
  const lines: string[] = [];
  for (const key of keys) {
    const last = lines.at(-1);
    if (last !== undefined && last.length + key.length + 3 <= width)
      lines[lines.length - 1] = `${last} | ${key}`;
    else lines.push(key);
  }
  return lines;
}

/** A type expression as TypeScript; nested lines are indented relative to the first. */
export function printExpr(t: TypeExpr): string {
  switch (t.kind) {
    case 'ref':
      return t.args ? `${t.name}<${t.args.map(printExpr).join(', ')}>` : t.name;
    case 'primitive':
      return t.name;
    case 'index':
      return `NonNullable<${t.base}[${quote(t.key)}]>`;
    case 'literal':
      return typeof t.value === 'string' ? quote(t.value) : String(t.value);
    case 'array':
      return `${paren(t.of)}[]`;
    case 'tuple':
      return `[${t.of.map(printExpr).join(', ')}]`;
    case 'optional':
      return `${paren(t.of)}?`;
    case 'rest':
      return `...${paren(t.of)}[]`;
    case 'union':
      return t.of.map(paren).join(' | ');
    case 'object':
      return block(t.fields);
    case 'require':
      return `Require<${printExpr(t.base)}, ${t.keys.map(quote).join(' | ')}>`;
    case 'never':
      return 'never';
    case 'otherString':
      return '(string & {})';
    case 'narrow': {
      const base = printExpr(t.base);
      const keys = t.omit.map(quote);
      const inline = `Omit<${base}, ${keys.join(' | ')}>`;
      // A long list goes one key per line, so the file stays readable.
      const omitted =
        keys.length === 0
          ? base
          : inline.length <= 80
            ? inline
            : `Omit<\n  ${base},\n${fill(keys, WIDTH - 4)
                .map((line) => `  | ${line}`)
                .join('\n')}\n>`;
      const groups = (t.oneOf ?? []).map(
        (branches) =>
          ` & (\n${branches.map((b) => `  | ${indentRest(block(b), '    ')}`).join('\n')}\n)`,
      );
      return `${omitted} & ${block(t.fields)}${groups.join('')}`;
    }
  }
}

/** Every type name an expression refers to. */
function names(t: TypeExpr, into: Set<string>): Set<string> {
  switch (t.kind) {
    case 'ref':
      into.add(t.name);
      for (const arg of t.args ?? []) names(arg, into);
      break;
    case 'index':
      into.add(t.base);
      break;
    case 'array':
    case 'optional':
    case 'rest':
      names(t.of, into);
      break;
    case 'tuple':
    case 'union':
      for (const item of t.of) names(item, into);
      break;
    case 'object':
      for (const f of t.fields) names(f.type, into);
      break;
    case 'require':
      into.add('Require');
      names(t.base, into);
      break;
    case 'narrow':
      names(t.base, into);
      for (const f of [...t.fields, ...(t.oneOf ?? []).flat(2)]) names(f.type, into);
      break;
  }
  return into;
}

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

/** A JSON value as a TypeScript expression. */
function printValue(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(printValue).join(', ')}]`;
  if (value !== null && typeof value === 'object') {
    const entries = Object.entries(value).map(
      ([key, v]) => `${IDENTIFIER.test(key) ? key : quote(key)}: ${printValue(v)}`,
    );
    return `{ ${entries.join(', ')} }`;
  }
  return typeof value === 'string' ? quote(value) : String(value);
}

function printHelper(h: Helper): string[] {
  const keys = Object.keys(h.values);
  if (h.kind === 'build') {
    return [
      `  /** ${/^[aeiou]/i.test(h.element) ? 'An' : 'A'} ${h.element} entry in the ${h.slice} slice, with ${keys.join(' and ')} filled in. */`,
      `  ${h.name}: (entry: OmitEach<${h.shape}, ${keys.map(quote).join(' | ')}>): ${h.shape} => ({`,
      '    ...entry,',
      ...keys.map((key) => `    ${key}: ${printValue(h.values[key])},`),
      '  }),',
    ];
  }
  return [
    `  /** The first ${h.element} entry in the ${h.slice} slice, if there is one. */`,
    `  ${h.name}: (parent: { ${h.element}?: ${h.item}[] }): ${h.shape} | undefined =>`,
    `    parent.${h.element}?.find((e): e is ${h.shape} => matches(e, ${printValue(h.values)})),`,
  ];
}

/** Which file declares each generated type, so a file can import another's. */
type Owners = Map<string, string>;

function printProfile(model: ProfileModel, hash: string, owners: Owners): string {
  const b = new FileBuilder('  ', false);
  const version = model.version ? `|${model.version}` : '';
  b.appendNoWrap(`${MARKER} from ${model.url}${version}. Do not edit.`);
  b.appendNoWrap(`// Source: ${model.source} ${hash}`);
  const used = new Set<string>();
  for (const d of model.decls) names(d.type, used);
  for (const h of model.helpers) used.add(h.item);
  const local = new Set(model.decls.map((d) => d.name));
  const foreign = [...used].filter((n) => !local.has(n) && n !== 'Require');
  const fhir = foreign.filter((n) => !owners.has(n)).sort();
  if (fhir.length > 0)
    b.appendNoWrap(`import type { ${fhir.join(', ')} } from '@medplum/fhirtypes';`);
  const files = [...new Set(foreign.flatMap((n) => owners.get(n) ?? []))].sort();
  for (const file of files) {
    const names = foreign.filter((n) => owners.get(n) === file).sort();
    b.appendNoWrap(`import type { ${names.join(', ')} } from './${file}.js';`);
  }
  const plumb = [
    ...(model.helpers.length > 0 ? ['matches'] : []),
    ...(model.helpers.some((h) => h.kind === 'build') ? ['type OmitEach'] : []),
    ...(used.has('Require') ? ['type Require'] : []),
  ];
  if (plumb.length > 0) b.appendNoWrap(`import { ${plumb.join(', ')} } from './_plumb.js';`);
  b.newLine();
  b.appendNoWrap(`/** The canonical URL of ${model.typeName}. */`);
  b.appendNoWrap(`export const ${model.typeName}ProfileUrl = ${quote(model.url)};`);
  for (const constant of model.constants) {
    b.newLine();
    b.appendNoWrap(`/** The codes of ${constant.name.slice(0, -'Codes'.length)}. */`);
    b.appendNoWrap(`export const ${constant.name} = [`);
    for (const c of constant.codes) b.appendNoWrap(`  ${printValue(c)},`);
    b.appendNoWrap('] as const;');
  }
  model.decls.forEach((d, i) => {
    b.newLine();
    if (i === 0) for (const line of docLines(model.doc, WIDTH - 3)) b.appendNoWrap(line);
    for (const line of `export type ${d.name} = ${printExpr(d.type)};`.split('\n'))
      b.appendNoWrap(line);
  });
  if (model.helpers.length > 0) {
    b.newLine();
    b.appendNoWrap(`/** Builders and readers for the slices of ${model.typeName}. */`);
    b.appendNoWrap(`export const ${model.typeName} = {`);
    for (const line of model.helpers.flatMap(printHelper)) b.appendNoWrap(line);
    b.appendNoWrap('};');
  }
  return b.toString();
}

const ROUTE = embed(routeSource);

const WRITE = embed(writeSource);

/**
 * The routing rows, by resource type then profile URL so a profile change
 * moves only its own lines, with the selected profiles' types and `route`.
 */
function printRoutes(routing: RoutingTable, typeNames: Map<string, string>): string {
  const selected = routing.profiles
    .flatMap((url) => {
      const name = typeNames.get(url);
      return name ? [[url, name] as const] : [];
    })
    .sort(([a], [b]) => (a < b ? -1 : 1));
  const lines = [`${MARKER}. Do not edit.`, "import type { Resource } from '@medplum/fhirtypes';"];
  lines.push("import { matches } from './_plumb.js';");
  for (const name of [...new Set(selected.map(([, n]) => n))].sort()) {
    lines.push(`import type { ${name} } from './${name}.js';`);
  }
  lines.push('', "/** Each selected profile's type, by canonical URL. */");
  if (selected.length === 0) lines.push('export type ProfileTypes = {};');
  else {
    lines.push('export type ProfileTypes = {');
    for (const [url, name] of selected) lines.push(`  ${quote(url)}: ${name};`);
    lines.push('};');
  }
  lines.push(
    '',
    '/** The canonical URL of a selected profile. */',
    'export type ProfileUrl = keyof ProfileTypes;',
    '',
    '/**',
    ' * The content that selects each profile: a row matches a resource when, for',
    ' * every key, the element holds one of its patterns (`matches` in _plumb.ts).',
    ' */',
    'const routes = {',
    ...Object.keys(routing.routes)
      .sort()
      .flatMap((type) => printRows(type, routing.routes[type] ?? [])),
    '} as const;',
    '',
    ROUTE,
    WRITE.replace('STAMPS', printStamps(routing.stamps)).replace(
      'MANAGED',
      printValue([...routing.managed].sort()),
    ),
  );
  return lines.join('\n');
}

function printRows(type: string, routes: Route[]): string[] {
  if (routes.length === 0) return [`  ${type}: [],`];
  const rows = [...routes].sort((a, b) => (a.profile < b.profile ? -1 : 1));
  return [
    `  ${type}: [`,
    ...rows.flatMap((row) => [
      '    {',
      `      profile: ${quote(row.profile)},`,
      `      parents: ${printValue(row.parents)},`,
      ...(row.keys.length === 0
        ? ['      keys: [],']
        : ['      keys: [', ...row.keys.map((key) => `        ${printValue(key)},`), '      ],']),
      '    },',
    ]),
    '  ],',
  ];
}

type RoutingTable = Pick<Routing, 'routes' | 'profiles' | 'stamps' | 'managed' | 'accepts'>;

const READS = embed(readsSource);

/** A table by profile URL, sorted, one entry per line. */
function printTable(name: string, type: string, rows: [string, unknown[]][]): string[] {
  if (rows.length === 0) return [`const ${name}: ${type} = {};`];
  const entries = [...rows].sort(([a], [b]) => (a < b ? -1 : 1));
  return [
    `const ${name}: ${type} = {`,
    ...entries.flatMap(([url, values]) =>
      values.length === 0
        ? [`  ${quote(url)}: [],`]
        : [`  ${quote(url)}: [`, ...values.map((v) => `    ${printValue(v)},`), '  ],'],
    ),
    '};',
  ];
}

/** What a typed read checks for each selected profile, and the checks themselves. */
function printReads(models: ProfileModel[], routing: RoutingTable): string {
  const selected = models.filter((m) => routing.profiles.includes(m.url));
  return [
    `${MARKER}. Do not edit.`,
    "import type { Reference, Resource, ResourceType } from '@medplum/fhirtypes';",
    "import { missing } from './_plumb.js';",
    "import type { ProfileTypes, ProfileUrl } from './_routes.js';",
    '',
    '/**',
    " * The paths each selected profile's type requires beyond @medplum/fhirtypes.",
    ' * A row lists alternatives, any one of which meets it (`missing` in _plumb.ts).',
    ' */',
    ...printTable(
      'required',
      'Record<ProfileUrl, readonly (readonly string[])[]>',
      selected.map((m) => [m.url, m.required]),
    ),
    '',
    '/** The stamps a read accepts as each profile: its own URL, and each selected profile deriving from it. */',
    ...printTable(
      'accepts',
      // Keyed by string, so the lookup still compiles when no profile is selected.
      'Partial<Record<string, readonly string[]>>',
      selected.map((m) => [m.url, routing.accepts[m.url] ?? [m.url]]),
    ),
    '',
    "/** Each profile's resource type. */",
    ...(selected.length === 0
      ? ['const typeOf: Partial<Record<string, ResourceType>> = {};']
      : [
          'const typeOf: Partial<Record<string, ResourceType>> = {',
          ...[...selected]
            .sort((a, b) => (a.url < b.url ? -1 : 1))
            .map((m) => `  ${quote(m.url)}: ${quote(m.sd.type)},`),
          '};',
        ]),
    '',
    READS,
  ].join('\n');
}

function printStamps(stamps: Record<string, string[]>): string {
  const urls = Object.keys(stamps).sort();
  if (urls.length === 0) return '{}';
  return `{\n${urls.map((url) => `  ${quote(url)}: ${printValue(stamps[url])},`).join('\n')}\n}`;
}

const MIGRATIONS = `${MARKER}. Do not edit.\n${embed(migrationsSource)}`;

/**
 * `_migrator.ts`, the migration bot's handler: every module the config lists,
 * by its import path from `out`. Not exported from the index, since the
 * modules import the index themselves.
 */
function printMigrator(
  modules: (string | { path: string; hash: string })[],
  restamp: boolean,
): string {
  const entries = modules.map((m) => (typeof m === 'string' ? { path: m } : m));
  const imports = [
    ...(restamp ? ["import { restamps } from './_restamp.js';"] : []),
    ...entries.map((m, i) => `import m${i} from ${quote(m.path)};`),
  ];
  const list = [
    ...entries.map((m, i) => ('hash' in m ? `{ ...m${i}, hash: ${quote(m.hash)} }` : `m${i}`)),
    ...(restamp ? ['...restamps'] : []),
  ].join(', ');
  return `${MARKER}. Do not edit.
import { handleMigrations } from './_migrations.js';
${imports.join('\n')}${imports.length > 0 ? '\n' : ''}
/** The migration bot's handler: its entry exports it, as \`export { handler } from './_migrator.js'\`. */
export const handler = handleMigrations([${list}]);
`;
}

/** The restamp's exclusion: its module's import path from `out`, and the hash of what it runs. */
export interface RestampExclusion {
  path: string;
  /** The restamps' hash, from `_routes.ts` as printed and the exclusion module. */
  hash: (routes: string) => string;
}

/**
 * `_restamp.ts`: Plumb's restamp migration for each type with routing rows,
 * which sets the stamps Plumb manages as `stampProfiled` would, keeps any
 * other URL, and leaves a record that routes to no single profile alone.
 * With an exclusion, each restamp leaves the records it names alone too, and
 * carries its hash, so the bot refuses a page once the exclusion is edited.
 */
function printRestamp(types: string[], exclude?: { path: string; hash: string }): string {
  const source = embed(restampSource).replace('TYPES', printValue(types));
  return [
    `${MARKER}. Do not edit.`,
    "import type { Resource, ResourceType } from '@medplum/fhirtypes';",
    "import type { JsonPatchOperation, MigrationDefinition } from './_migrations.js';",
    "import { RoutingError, stampProfiled } from './_routes.js';",
    ...(exclude ? [`import exclude from ${quote(exclude.path)};`] : []),
    '',
    exclude
      ? source.replace(
          '  transform: restamp,\n',
          `  transform: restamp,\n  exclude,\n  hash: ${quote(exclude.hash)},\n`,
        )
      : source,
  ].join('\n');
}

/**
 * Every file Plumb writes to `out`: one per profile and per Questionnaire in
 * `content`, the index, the shared helpers, the routes and the reads, the
 * operation contracts when the config lists `operations`, and the typed bot
 * handlers, printed by `printBots`, when it declares `bots`.
 */
export function printFiles(
  models: ProfileModel[],
  hashOf: (model: ProfileModel) => string,
  routing: RoutingTable = { routes: {}, profiles: [], stamps: {}, managed: [], accepts: {} },
  questionnaires: { name: string; file: string }[] = [],
  operations: string[] = [],
  bots?: string,
  migrations?: (string | { path: string; hash: string })[],
  restamp: boolean | RestampExclusion = false,
): Map<string, string> {
  const owners: Owners = new Map(
    models.flatMap((m) => m.decls.map((d): [string, string] => [d.name, m.typeName])),
  );
  const files = new Map<string, string>();
  for (const model of models) {
    files.set(`${model.typeName}.ts`, printProfile(model, hashOf(model), owners));
  }
  const index = new FileBuilder('  ', false);
  index.appendNoWrap(`${MARKER}. Do not edit.`);
  index.appendNoWrap("export type { Require } from './_plumb.js';");
  index.appendNoWrap(
    "export { createProfiled, type ProfiledClient, type ProfileTypes, type ProfileUrl, RoutingError, route, stampProfiled, updateProfiled } from './_routes.js';",
  );
  index.appendNoWrap(
    "export { asProfiled, isProfiled, pickProfiled, type ProfiledQuery, type ProfiledReader, ProfileReadError, type ProfileReadFailure, readProfiled, searchProfiled } from './_reads.js';",
  );
  if (operations.length > 0) {
    index.appendNoWrap(
      "export { callOperation, defineOperation, handleOperation, type OperationClient, type OperationContract, OperationError, type OperationSide, type SideInput, type SideOutput, type StandardSchemaV1 } from './_operations.js';",
    );
    files.set('_operations.ts', OPERATIONS);
  }
  if (migrations) {
    index.appendNoWrap(
      "export { defineMigration, handleMigrations, type JsonPatchOperation, type MigrationClient, type MigrationDefinition, type MigrationForecast, type MigrationPage, type MigrationPageResult } from './_migrations.js';",
    );
    files.set('_migrations.ts', MIGRATIONS);
    files.set('_migrator.ts', printMigrator(migrations, restamp !== false));
  }
  if (bots) {
    index.appendNoWrap(
      "export { type BotInputs, type BotSecrets, defineBot, type PlumbBotEvent } from './_bots.js';",
    );
    files.set('_bots.ts', bots);
  }
  for (const q of questionnaires) files.set(`${q.name}Answers.ts`, q.file);
  const names = [
    ...models.map((m) => m.typeName),
    ...questionnaires.map((q) => `${q.name}Answers`),
  ];
  for (const name of names.sort()) {
    index.appendNoWrap(`export * from './${name}.js';`);
  }
  files.set('index.ts', index.toString());
  files.set('_plumb.ts', questionnaires.length > 0 ? HELPERS + ANSWERS : HELPERS);
  const routes = printRoutes(routing, new Map(models.map((m) => [m.url, m.typeName])));
  files.set('_routes.ts', routes);
  if (migrations && restamp !== false) {
    const exclude =
      restamp === true ? undefined : { path: restamp.path, hash: restamp.hash(routes) };
    files.set('_restamp.ts', printRestamp(Object.keys(routing.routes).sort(), exclude));
  }
  files.set('_reads.ts', printReads(models, routing));
  return files;
}
